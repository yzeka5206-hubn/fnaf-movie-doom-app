#!/usr/bin/env python3
"""Compare fixed-pose solid-skin engine screenshots; NOT an Android/game test.

Usage: compare_fixture_frames.py frame-0.png frame-15.png
The room generated by make_engine_fixture.py --solid-skin marks the three
models cyan, green and magenta. Their silhouettes should all differ between
valid Walk poses. The unpatched ES backend should fail (unchanged T-pose).
Image comparison cannot prove the shapes are anatomically correct; use the
IQM numeric tests and inspect/compare the frames as well.
"""
import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image


def masks(path):
    pixels = np.asarray(Image.open(path).convert('RGB'), dtype=np.int16)
    r, g, b = (pixels[:, :, i] for i in range(3))
    return {
        'world_or_actor_0_cyan': (g > 2*r) & (b > 2*r) & (g > 100) & (b > 100),
        'legs_or_actor_1_green': (g > 2*r) & (g > 2*b) & (g > 100),
        'arm_or_actor_2_magenta': (r > 2*g) & (b > 2*g) & (r > 100) & (b > 100),
    }


def compare(frame0, frame15, min_changed=5, min_area=10):
    first, second = masks(frame0), masks(frame15)
    results = {}
    for name in first:
        a, b = first[name], second[name]
        if a.shape != b.shape:
            raise ValueError('fixture screenshots have different dimensions')
        changed = int(np.logical_xor(a, b).sum())
        areas = [int(a.sum()), int(b.sum())]
        # A whole-screen-colored explosion is not acceptable as an actor.
        max_area = int(a.size * .20)
        passed = min(areas) >= min_area and max(areas) <= max_area and changed >= min_changed
        results[name] = {'areas': areas, 'changed_pixels': changed, 'pass': bool(passed)}
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('frame0', type=Path)
    parser.add_argument('frame15', type=Path)
    args = parser.parse_args()
    results = compare(args.frame0, args.frame15)
    print(json.dumps(results, indent=2))
    if not all(r['pass'] for r in results.values()):
        raise SystemExit('FAIL: at least one fixed-pose silhouette did not change or is invalid')
    print('PASS: all three visible test actor silhouettes changed')


if __name__ == '__main__':
    main()
